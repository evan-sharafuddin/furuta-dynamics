function [dx,y] = furuta_grey(t,x,u,...
    m1,m2,L1,L2,Jaddl,b1,b2,Ke,Km,...
    k1,k2,k3, varargin)

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% STATES
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
theta1    = x(1);
theta2    = x(2);
i         = x(3);
theta1dot = x(4);
theta2dot = x(5);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% CONSTANTS
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
Lm = 1.6e-3;
Rm = 1.47;
g  = 9.81;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% GEOMETRY
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
l1 = L1/2;
l2 = L2/2;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% INERTIAS
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
J1 = (1/12)*m1*L1^2;
J2 = (1/12)*m2*L2^2;

J1hat = J1 + m1*l1^2;
J2hat = J2 + m2*l2^2;
J0hat = J1hat + m2*L1^2 + Jaddl;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% MOTOR TORQUE
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
tau = Km * i;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% SHORTHANDS
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
s2  = sin(theta2);
c2  = cos(theta2);
s2_2 = sin(2*theta2);

den = (J0hat*J2hat + J2hat^2*(s2^2) - (m2^2)*(L1^2)*(l2^2)*(c2^2));

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% NONLINEAR DYNAMICS (DIRECT FROM MODEL)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

% -------------------------
% theta1 acceleration
% -------------------------
theta1ddot = ( ...
   -J2hat*b1*theta1dot ...
   + m2*L1*l2*c2*b2*theta2dot ...
   - J2hat^2*s2_2*theta1dot*theta2dot ...
   - 0.5*J2hat*m2*L1*l2*c2*s2_2*theta1dot^2 ...
   + J2hat*m2*L1*l2*s2*theta2dot^2 ...
   + J2hat*tau ...
   + 0.5*(m2^2)*(l2^2)*L1*s2_2*g ...
   ) / den;

% -------------------------
% theta2 acceleration
% -------------------------
theta2ddot = ( ...
   m2*L1*l2*c2*b1*theta1dot ...
   - b2*(J0hat + J2hat*(s2^2))*theta2dot ...
   + m2*L1*l2*J2hat*c2*s2_2*theta1dot*theta2dot ...
   - 0.5*s2_2*(J0hat*J2hat + J2hat^2*(s2^2))*theta1dot^2 ...
   - 0.5*(m2^2)*(L1^2)*(l2^2)*s2_2*theta2dot^2 ...
   - m2*L1*l2*c2*tau ...
   - m2*l2*s2*(J0hat + J2hat*(s2^2))*g ...
   ) / den;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% ELECTRICAL DYNAMICS
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
idot = (u - Rm*i - Ke*theta1dot)/Lm;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% STATE EQUATIONS
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
dx = zeros(5,1);

dx(1) = theta1dot;
dx(2) = theta2dot;
dx(3) = idot;
dx(4) = theta1ddot;
dx(5) = theta2ddot;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% OUTPUTS
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
y = [
    k1*theta1
    k2*theta2
    k3*i
];

end